# max() function for finding maximum of the given data.
big=max(2,4,1,6,4,7,9);
print('bigest number is: ',big);

#min() function for finding minimum of the given data.
small=min(2,34,5,5,2,5,3,5,34,54,3);
print('smallest number is : ' ,small);

# It also works on the string:
big=max('hii mittar');
print('biggest string is: ',big);

smallest=min('hellomittar');
print('smallest string is : ',smallest);